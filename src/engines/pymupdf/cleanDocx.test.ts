import { strFromU8, strToU8, unzipSync, zipSync } from 'fflate'
import { describe, expect, it } from 'vitest'
import { cleanDocx } from './cleanDocx'

// A Word file as pdf2docx makes it, with python-docx's template details.
const TYPES = `<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/><Default Extension="jpeg" ContentType="image/jpeg"/><Override PartName="/docProps/thumbnail.jpeg" ContentType="image/jpeg"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`
const RELS = `<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/><Relationship Id="rId3" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/thumbnail" Target="docProps/thumbnail.jpeg"/></Relationships>`
const CORE = `<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:creator>python-docx</dc:creator><dc:description>generated by python-docx</dc:description><dcterms:created>2013-12-23T23:15:00Z</dcterms:created></cp:coreProperties>`
const APP = `<Properties><Application>Microsoft Macintosh Word</Application><Pages>1</Pages></Properties>`
const DOCUMENT =
  '<w:document><w:body><w:p><w:r><w:t>Hello</w:t></w:r></w:p></w:body></w:document>'
// A picture in the document: bytes that must come through untouched.
const picture = new Uint8Array(400).map((_, i) => (i * 31) % 256)

const docx = () =>
  zipSync({
    '[Content_Types].xml': strToU8(TYPES),
    '_rels/.rels': strToU8(RELS),
    'docProps/core.xml': strToU8(CORE),
    'docProps/app.xml': strToU8(APP),
    'docProps/thumbnail.jpeg': new Uint8Array([0xff, 0xd8, 0xff]),
    'word/document.xml': strToU8(DOCUMENT),
    'word/media/image1.png': picture,
  })

describe('cleaning a Word file from pdf2docx', () => {
  const files = unzipSync(cleanDocx(docx()))
  const text = (name: string) => strFromU8(files[name])

  it('clears the template’s author, comment and dates', () => {
    expect(text('docProps/core.xml')).not.toMatch(/python-docx|2013|creator/)
    expect(text('docProps/core.xml')).toContain('<cp:coreProperties')
  })

  it('names Tuls as the app', () => {
    expect(text('docProps/app.xml')).toContain(
      '<Application>Tuls</Application>',
    )
    expect(text('docProps/app.xml')).not.toContain('Macintosh')
  })

  it('drops the template’s thumbnail, and every mention of it', () => {
    expect(files['docProps/thumbnail.jpeg']).toBeUndefined()
    expect(text('_rels/.rels')).not.toContain('thumbnail')
    expect(text('_rels/.rels')).toContain('word/document.xml')
    expect(text('[Content_Types].xml')).not.toContain('thumbnail')
    // Pictures in the document still have their type.
    expect(text('[Content_Types].xml')).toContain('Extension="jpeg"')
  })

  it('leaves the document itself as it was', () => {
    expect(text('word/document.xml')).toBe(DOCUMENT)
    expect(files['word/media/image1.png']).toEqual(picture)
  })
})
